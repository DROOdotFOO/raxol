  @debug_highlight_truecolor :io_lib.format("#~2.16.0B~2.16.0B~2.16.0B", [
                               dh_r,
                               dh_g,
                               dh_b
                             ])
                             |> IO.iodata_to_binary()

  # 256-color: the nearest CHROMATIC blue cube entry to the solved tint --
  # cube 24, rgb(0,95,135). Deliberately NOT the nearest-RGB pick (that is
  # gray-ramp 237, the exact hue-erasing collapse
  # `Raxol.UI.Theming.Ansi16Salience`'s moduledoc documents); category
  # preservation outranks raw distance, same ranked priority as that
  # module's own table.
  @debug_highlight_256 {:xterm256, 24}

  # 16-color: the blue slot (SGR bg 44), per the category-preserving
  # downgrade rule -- blue stays blue, never gray.
  @debug_highlight_ansi16 {:ansi16, 4}

  @typedoc """
  A background tint in the terminal-neutral encoding consumers (e.g.
  `Raxol.Harness.Surface.ViewText`) render to SGR: a `"#RRGGBB"` hex
  (24-bit), `{:xterm256, 0..255}` (indexed), or `{:ansi16, 0..15}` (basic).
  """
  @type bg_tint ::
          String.t() | {:xterm256, 0..255} | {:ansi16, 0..15}

  @doc """
  The `:debug_highlight_bg` role -- the pale-blue selection tint painted
  under a DevTools-hovered harness footer group -- resolved per capability
  tier. See the section comment above for each tier's derivation.
  """
  @spec debug_highlight_bg(:truecolor | :xterm256 | :ansi16) :: bg_tint()
  def debug_highlight_bg(:truecolor), do: @debug_highlight_truecolor
  def debug_highlight_bg(:xterm256), do: @debug_highlight_256
  def debug_highlight_bg(:ansi16), do: @debug_highlight_ansi16

  @doc """
  Resolves the `:debug_highlight_bg` role for a terminal capability record
  (`%Raxol.Terminal.Capabilities{}`-shaped; matched as a map per the
  cross-package pattern convention) or `nil`.

  The tier ladder: `truecolor: true` -> 24-bit; `tier: :core_minus` (not a
  tty, or no probe response -- the record's own "assume least" bucket) ->
  ANSI16 blue; any other probed record -> the 256 cube entry. `nil` (no
  capability record at all -- the demos' default) also resolves to the 256
  entry: the honest middle ground, near-universally supported and still
  category-true where it isn't.
  """
  @spec debug_highlight_bg_for(map() | nil) :: bg_tint()
  def debug_highlight_bg_for(%{truecolor: true}),
    do: debug_highlight_bg(:truecolor)

  def debug_highlight_bg_for(%{tier: :core_minus}),
    do: debug_highlight_bg(:ansi16)

  def debug_highlight_bg_for(%{tier: _tier}),
    do: debug_highlight_bg(:xterm256)

  def debug_highlight_bg_for(_nil_or_unknown),
    do: debug_highlight_bg(:xterm256)

