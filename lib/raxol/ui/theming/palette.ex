  # ===========================================================================
  # ANSI 256 cube (16-231) and grayscale ramp (232-255)
  # ===========================================================================
  # The 216-color cube has two competing step formulas in the codebase (see
  # inventory §5.1). :xterm_accurate (0,95,135,175,215,255) is the real xterm
  # 256-color formula, from Raxol.UI.Theming.Colors.@ansi_216_colors.
  # :naive_linear (0,51,102,153,204,255) is what
  # Raxol.Style.Colors.Formats.ansi_to_rgb/1 and
  # Raxol.Terminal.ANSI.SixelPalette both actually use -- preserved here
  # under its own name rather than silently "fixed", since a caller may
  # depend on its current (inaccurate but consistent) output.

  @spec cube_level(:xterm_accurate, 0..5) :: 0..255
  defp cube_level(:xterm_accurate, 0), do: 0
  defp cube_level(:xterm_accurate, n), do: 55 + n * 40
  defp cube_level(:naive_linear, n), do: n * 51

  @doc """
  Generates the 216-entry ANSI 256-color cube (indices 16-231) under the
  given step formula. Returns `[{index, {r, g, b}}]`.
  """
  @spec ansi_256_cube(ansi_256_cube_formula()) :: [{16..231, rgb()}]
  def ansi_256_cube(formula) when formula in [:xterm_accurate, :naive_linear] do
    for r <- 0..5, g <- 0..5, b <- 0..5 do
      index = 16 + 36 * r + 6 * g + b

      {index,
       {cube_level(formula, r), cube_level(formula, g), cube_level(formula, b)}}
    end
  end

  @doc """
  Generates the 24-entry ANSI 256-color grayscale ramp (indices 232-255).
  Returns `[{index, {level, level, level}}]`. Unlike the cube, every source
  in the codebase agrees on this formula -- there is only one variant.
  """
  @spec ansi_256_grayscale() :: [{232..255, rgb()}]
  def ansi_256_grayscale do
    for i <- 0..23 do
      level = 8 + i * 10
      {232 + i, {level, level, level}}
    end
  end

