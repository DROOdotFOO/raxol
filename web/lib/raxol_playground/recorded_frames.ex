defmodule RaxolPlayground.RecordedFrames do
  @moduledoc """
  Recorded terminal frames served statically: the landing hero's switchable
  examples and one rendered preview per gallery demo.

  Generated by `scripts/gen_landing_frames.exs` at the repo root (real
  `Raxol.Headless` sessions rendered through `TerminalBridge.buffer_to_html/2`)
  and committed under `priv/hero_frames/` and `priv/demo_previews/`. Embedded
  at compile time so the dead render before the LiveView socket connects
  already carries frame one and every gallery preview.
  """

  hero_dir = Path.expand("../../priv/hero_frames", __DIR__)
  preview_dir = Path.expand("../../priv/demo_previews", __DIR__)

  # One directory per hero example. frame_0..frame_9 sort lexically; pad the
  # generator's names before recording a sequence that reaches double digits.
  hero_examples =
    hero_dir
    |> File.ls!()
    |> Enum.sort()
    |> Enum.filter(&File.dir?(Path.join(hero_dir, &1)))

  hero_paths =
    Map.new(hero_examples, fn name ->
      dir = Path.join(hero_dir, name)
      paths = dir |> File.ls!() |> Enum.sort() |> Enum.map(&Path.join(dir, &1))
      {name, paths}
    end)

  for {_name, paths} <- hero_paths, path <- paths do
    @external_resource path
  end

  @hero_frames Map.new(hero_paths, fn {name, paths} ->
                 {name, Enum.map(paths, &File.read!/1)}
               end)

  preview_paths =
    preview_dir
    |> File.ls!()
    |> Enum.sort()
    |> Enum.map(&Path.join(preview_dir, &1))

  for path <- preview_paths do
    @external_resource path
  end

  @previews Map.new(preview_paths, fn path ->
              {Path.basename(path, ".html"), File.read!(path)}
            end)

  @doc "Recorded frames for one hero example, in playback order."
  @spec hero_frames(String.t()) :: [String.t()]
  def hero_frames(example), do: Map.get(@hero_frames, example, [])

  @doc "Every hero example name that has recorded frames."
  @spec hero_examples() :: [String.t()]
  def hero_examples, do: @hero_frames |> Map.keys() |> Enum.sort()

  @doc "Rendered preview frame for a catalog demo name, or nil."
  @spec preview(String.t()) :: String.t() | nil
  def preview(name), do: Map.get(@previews, slug(name))

  @doc "The slug a demo name is stored under (mirrors the generator)."
  @spec slug(String.t()) :: String.t()
  def slug(name) do
    name
    |> String.downcase()
    |> String.replace(~r/[^a-z0-9]+/, "_")
    |> String.trim("_")
  end
end
